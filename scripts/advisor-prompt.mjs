export function buildSystemPrompt(options = {}) {
  const intent = options.intent || 'general';
  const mode = options.mode || 'advisor';
  let profile = options.promptProfile || getPromptProfile(intent, mode);
  if (options.unknownAdvancement) profile = 'unknown_entity';
  else if (options.answerStyle === 'roadmap') profile = 'build_roadmap';
  else if (options.answerStyle === 'catalog') profile = 'catalog_skills';
  else if (options.answerStyle === 'full_list') profile = 'full_list_skills';
  const className = options.className || null;
  const tier = options.tier || (className ? getClassProfile(className).tier : 'full');

  const store = loadAdvisorStore();
  const ruleBullets = (store.rulesSummary?.bullets || []).slice(0, 12).join('\n- ');
  const addon = mode === 'wizard'
    ? INTENT_ADDONS.wizard
    : (INTENT_ADDONS[profile] || INTENT_ADDONS[intent] || '');

  const goalOverrideNote = options.goalOverride?.sessionFocus === 'reject_prior'
    ? `\n## 会话目标重置\n- 用户已否定此前职业假设；勿引用被否定的主职/兼职建议。当前焦点：${
      options.goalOverride.advancementName || options.goalOverride.mainClass || '见用户最新问句'
    }。\n`
    : '';

  const tierAudit = className ? formatTierAuditContext(className) : '';

  return `${buildBaseRules(className, tier)}

## 硬规则（必须遵守）${BASE_RULES_TAIL}
${STYLE_RULES}
${addon}${goalOverrideNote}
${tierAudit ? `\n## 档位检查（勿向用户复述标题）\n${tierAudit}\n` : ''}

## 全局规则摘要（仅供你判断，不要原文复述给用户）
- ${ruleBullets}`;
}

export function buildUserMessage(query, contextMarkdown, options = {}) {
  const mode = options.mode || 'advisor';
  const intent = options.intent || 'general';
  const wizardNote = mode === 'wizard'
    ? '\n\n（创建页陪跑：以页面与熟练账本为准；只评价/解释已选内容，禁止推销未选项；起始特性选满后才评价组合。）'
    : '';
  const styleNote = options.answerStyle === 'roadmap'
    ? `\n\n（roadmap 模式：通用分阶段 build 建议，可多条思路；须结合 L2 检索灵活发挥；${
      options.hasRoadmapOutline ? '有路线骨架时勿改事实性门槛与等级节点；' : ''
    }结尾须写「仅作参考」免责声明。）`
    : options.answerStyle === 'catalog'
      ? '\n\n（catalog 模式：按目录给出各流派/位阶总数与示例，勿逐条列全表。）'
      : options.answerStyle === 'full_list'
        ? '\n\n（full_list 模式：用户已追问完整列表，须尽量枚举上下文中的全部技能名。）'
        : '';

  return `【用户问题】
${query}

【检索上下文】
${contextMarkdown}

【路由】模式=${mode}；意图=${intent}${wizardNote}${styleNote}

请基于以上检索上下文回答。只使用上下文中出现的具体名称。
排版要求：助理口吻、稍正式；每点一行，点之间空一行；不用 Markdown 标题/加粗/编号列表。`;
}

export function buildChatMessages(query, contextMarkdown, options = {}) {
  const messages = [
    { role: 'system', content: buildSystemPrompt(options) },
  ];
  const history = options.conversationHistory || [];
  for (const turn of history) {
    if (turn.user) messages.push({ role: 'user', content: turn.user });
    if (turn.assistant) messages.push({ role: 'assistant', content: turn.assistant });
  }
  messages.push({ role: 'user', content: buildUserMessage(query, contextMarkdown, options) });
  return messages;
}
